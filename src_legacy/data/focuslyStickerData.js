// Helper function to get sticker URL
export const getStickerUrl = (fileName) => {
  return `/assets/focusly/stickers/${fileName}`;
};

// Helper function to search stickers
export const searchStickers = (query) => {
  if (!query) return FOCUSLY_STICKERS;
  
  const lowerQuery = query.toLowerCase();
  return FOCUSLY_STICKERS.filter(sticker => 
    sticker.name.toLowerCase().includes(lowerQuery) ||
    sticker.keywords.some(keyword => keyword.includes(lowerQuery)) ||
    sticker.description.toLowerCase().includes(lowerQuery)
  );
};

// Helper function to filter by category
export const filterStickersByCategory = (category) => {
  if (category === 'all') return FOCUSLY_STICKERS;
  return FOCUSLY_STICKERS.filter(sticker => sticker.category === category);
};
